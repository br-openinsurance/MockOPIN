    branch                                                      VARCHAR,
    code                                                        VARCHAR,
    description                                                 VARCHAR,
    internal_code                                               VARCHAR,
    susep_process_number                                        VARCHAR,
    lmi_amount                                                  VARCHAR,
    lmi_unit_type                                               VARCHAR,
    lmi_sublimit                                                BOOLEAN,
    term_start_date                                             DATE,
    term_end_date                                               DATE,
    main_coverage                                               BOOLEAN,
    trigger_event                                               VARCHAR,
    financial_type                                              VARCHAR,
    benefit_payment_modality                                    VARCHAR,
    created_at                                                  TIMESTAMP,
    created_by                                                  VARCHAR,
    updated_at                                                  TIMESTAMP,
    updated_by                                                  VARCHAR,
    hibernate_status                                            VARCHAR,
    FOREIGN KEY (person_insured_object_id) REFERENCES person_insured_objects (person_insured_object_id) ON DELETE CASCADE
);

